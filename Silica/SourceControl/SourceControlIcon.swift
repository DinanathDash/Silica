/// In-memory cache for rendered SVG template NSImages.
@MainActor
final class SourceControlIconStore {
    static let shared = SourceControlIconStore()

    private var cache: [SourceControlIconType: NSImage] = [:]

    private init() {}

    func image(for type: SourceControlIconType) -> NSImage? {
        if let cached = cache[type] {
            return cached
        }
        guard let data = type.rawSVG.data(using: .utf8),
              let nsImage = NSImage(data: data) else {
            return nil
        }
        nsImage.isTemplate = true
        cache[type] = nsImage
        return nsImage
    }
}

/// SwiftUI component that renders a crisp SVG icon with template tinting support.
struct SourceControlIcon: View {
    let type: SourceControlIconType
    var size: CGFloat = 13

    var body: some View {
        if let image = SourceControlIconStore.shared.image(for: type) {
            Image(nsImage: image)
                .resizable()
                .renderingMode(.template)
                .aspectRatio(contentMode: .fit)
                .frame(width: size, height: size)
        }
    }
}
